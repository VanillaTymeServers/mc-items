import fs from "node:fs";
import path from "node:path";

const [langPath, rendersDir] = process.argv.slice(2);
if (!langPath || !rendersDir) {
    console.error("usage: pnpm generate <en_us.json> <renders items folder>");
    process.exit(1);
}

const root = path.resolve(import.meta.dirname, "..");
const iconsDir = path.join(root, "icons");
const lang: Record<string, string> = JSON.parse(
    fs.readFileSync(langPath, "utf8"),
);

const ids = fs
    .readdirSync(rendersDir)
    .filter((file) => file.endsWith(".png"))
    .map((file) => file.slice(0, -4))
    .sort();

const items: Record<string, string> = {};
const missing: string[] = [];
for (const id of ids) {
    const name = lang[`item.minecraft.${id}`] ?? lang[`block.minecraft.${id}`];
    if (name) {
        items[id] = name;
    } else {
        missing.push(id);
    }
}
if (missing.length > 0) {
    console.error(`no english name for: ${missing.join(", ")}`);
    process.exit(1);
}

fs.rmSync(iconsDir, { recursive: true, force: true });
fs.mkdirSync(iconsDir);
for (const id of ids) {
    fs.copyFileSync(
        path.join(rendersDir, `${id}.png`),
        path.join(iconsDir, `${id}.png`),
    );
}

const entries = ids.map(
    (id) => `\t${JSON.stringify(id)}: ${JSON.stringify(items[id])},`,
);
fs.writeFileSync(
    path.join(root, "items.ts"),
    `// Generated by scripts/generate.ts from Minecraft's en_us.json. Do not edit by hand.\n\nexport const items = {\n${entries.join("\n")}\n} as const\n`,
);
console.log(`wrote ${ids.length} items`);
